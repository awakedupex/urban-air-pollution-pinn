# ---------------------------------------------------------------- 2 model
md(r"""
## 2. Mathematical model

Conservation of mass in a well-mixed layer of depth $H(t)$, with uniform wind, K-theory diffusion, linear removal and
a separable emission source, gives the 2D advection–diffusion–reaction equation

$$
\frac{\partial C}{\partial t} + u(t)\frac{\partial C}{\partial x} + v(t)\frac{\partial C}{\partial y}
= D\nabla^2 C - \lambda C + \frac{q(x,y)\,g(\tau)}{\max\{H(t),H_{\min}\}} .
$$

| Symbol | Meaning | Status |
|---|---|---|
| $C$ | PM$_{2.5}$ (µg m$^{-3}$) | observed at monitors |
| $u, v$ | 10 m wind (m s$^{-1}$) | estimated (ERA5) |
| $H$ | boundary-layer height (m), floored at $H_{\min}=50$ m | estimated (ERA5) |
| $D$ | eddy diffusivity (m$^2$ s$^{-1}$), bounded to [10, 2000] | calibrated |
| $\lambda$ | removal rate, $5\times10^{-6}$ s$^{-1}$ | fixed |
| $q(x,y)\ge 0$, $g(\tau)$ | emission flux field and 24-h profile (mean 1) | calibrated |

**Assumptions:** well-mixed layer (2D), spatially uniform wind, constant isotropic $D$, linear removal,
separable emissions, unknown inflow (weak outflow condition only), no entrainment term.

### Dimensionless groups
Scaling $x' = (x-x_c)/L$, $t' = 2t/T-1$, $C' = C/C_{\mathrm{ref}}$ gives coefficients $U=uT/2L$, $K=DT/2L^2$,
$\Lambda=\lambda T/2$. The physical groups are the Péclet number $\mathrm{Pe}=\bar u\ell/D$ and the Damköhler number
$\mathrm{Da}=\lambda\ell/\bar u$. We compute them from the real forcing:
""")

code(r"""
from experiments.make_synthetic_twin import domain_km
xmin, xmax, ymin, ymax = domain_km(cfg["domain"])
ell = max(xmax - xmin, ymax - ymin) * 1e3       # m
lam = cfg["physics"]["lam"]
for w, f in forcing.items():
    ubar = f.wind_speed_10m.mean()
    print(f"{w}: mean wind {ubar:.2f} m/s | advection time l/u = {ell / ubar / 3600:.1f} h | "
          f"Pe = {ubar * ell / 1000:.0f}–{ubar * ell / 100:.0f} (D = 1000–100 m²/s) | Da = {lam * ell / ubar:.2f} | "
          f"H range {f.blh.min():.0f}–{f.blh.max():.0f} m")
""")

md(r"""
**Interpretation.** $\mathrm{Pe}\gg 1$: transport is dominated by the wind, and diffusion is a small correction —
so we should *expect* $D$ to be poorly identifiable. $\mathrm{Da}\ll 1$: removal is slow compared with transit.
Air crosses the city in 7–11 hours, so hourly data can, in principle, see transport between stations. The ERA5 mixing
height falls to 15–25 m on calm nights in these windows (and to ~10 m in the twin's forcing), which motivates the floor $H_{\min}=50$ m.
""")

