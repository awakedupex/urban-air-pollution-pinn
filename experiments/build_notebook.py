k = np.logspace(-6, -2.5, 200)                       # wavenumber (1/m)
fig, axs = plt.subplots(1, 2, figsize=(10, 3.2))
for D in (100, 300, 1000):
    axs[0].loglog(2 * np.pi / k / 1e3, (D * k**2 + lam) * 3600, label=f"D = {D} m²/s")
axs[0].axhline(lam * 3600, color="k", ls=":", label="λ alone")
axs[0].set(xlabel="wavelength (km)", ylabel="decay rate −Re σ (1/h)", title="Every Fourier mode decays"); axs[0].legend()

# Equilibrium: uniform source and removal with the reference solver vs the exact solution.
g = Grid(-1e4, 1e4, -1e4, 1e4, 21, 21)
S0, lam_demo = 2e-3, 1e-4
exact = lambda t: S0 / lam_demo * (1 - np.exp(-lam_demo * t))
sol = solve_adr(g, np.zeros(g.shape), 50_000, lambda t: 1.5, lambda t: -0.5, 100.0, lam_demo,
                lambda X, Y, t: S0, exact, save_every=2500.0)
